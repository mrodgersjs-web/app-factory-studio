MODELS_PY = '''"""Schema and validation for __NAME__.

Generated by app-factory __VERSION__ from spec __SHA12__. Regenerate instead of editing.
"""

from __future__ import annotations

import datetime

SCHEMA: dict[str, dict] = __SCHEMA__

TRUE_WORDS = {"true", "1", "yes", "y", "on"}
FALSE_WORDS = {"false", "0", "no", "n", "off"}


class ValidationError(ValueError):
    """Input does not match the schema. ``errors`` maps field name to problem."""

    def __init__(self, errors: dict[str, str]) -> None:
        super().__init__("; ".join(f"{k}: {v}" for k, v in sorted(errors.items())))
        self.errors = errors


def entity_names() -> list[str]:
    return list(SCHEMA)


def fields(entity: str) -> list[dict]:
    if entity not in SCHEMA:
        raise KeyError(f"unknown entity: {entity}")
    return SCHEMA[entity]["fields"]


def coerce(kind: str, value: object) -> object:
    """Convert ``value`` to the schema type ``kind`` or raise ValueError."""
    if kind == "str":
        if not isinstance(value, str):
            raise ValueError("expected text")
        if not value.strip():
            raise ValueError("must not be blank")
        return value
    if kind == "bool":
        if isinstance(value, bool):
            return value
        if isinstance(value, str) and value.strip().lower() in TRUE_WORDS:
            return True
        if isinstance(value, str) and value.strip().lower() in FALSE_WORDS:
            return False
        raise ValueError("expected true or false")
    if kind == "int":
        if isinstance(value, int) and not isinstance(value, bool):
            return value
        if isinstance(value, str):
            try:
                return int(value.strip())
            except ValueError:
                pass
        raise ValueError("expected a whole number")
    if kind == "float":
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return float(value)
        if isinstance(value, str):
            try:
                return float(value.strip())
            except ValueError:
                pass
        raise ValueError("expected a number")
    if kind == "date":
        if isinstance(value, str):
            try:
                return datetime.date.fromisoformat(value.strip()).isoformat()
            except ValueError:
                pass
        raise ValueError("expected a date as YYYY-MM-DD")
    raise ValueError(f"unknown type: {kind}")


def validate(entity: str, data: object, *, partial: bool = False) -> dict:
    """Return cleaned data or raise ValidationError listing every problem.

    ``partial=True`` checks only the fields given (used for updates and filters).
    """
    if not isinstance(data, dict):
        raise ValidationError({"_": "expected an object"})
    known = {f["name"]: f for f in fields(entity)}
    errors: dict[str, str] = {}
    clean: dict = {}
    for key in data:
        if key not in known:
            errors[key] = "unknown field"
    for name, spec in known.items():
        if name not in data:
            if not partial:
                if spec["required"]:
                    errors[name] = "required"
                else:
                    clean[name] = None
            continue
        value = data[name]
        if value is None:
            if spec["required"]:
                errors[name] = "required"
            else:
                clean[name] = None
            continue
        try:
            clean[name] = coerce(spec["type"], value)
        except ValueError as exc:
            errors[name] = str(exc)
    if partial and not data:
        errors["_"] = "no fields given"
    if errors:
        raise ValidationError(errors)
    return clean
'''

STORE_PY = '''"""SQLite persistence for __NAME__. One table per entity, integer ids."""

from __future__ import annotations

import sqlite3
import threading

from . import models

SQL_TYPES = {"str": "TEXT", "int": "INTEGER", "float": "REAL", "bool": "INTEGER", "date": "TEXT"}


class Store:
    """CRUD over SQLite. ``path=":memory:"`` keeps data in memory."""

    def __init__(self, path: str = ":memory:") -> None:
        self._conn = sqlite3.connect(path, check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        self._lock = threading.Lock()
        with self._lock, self._conn:
            for entity in models.entity_names():
                cols = ", ".join(
                    f'"{f["name"]}" {SQL_TYPES[f["type"]]}' for f in models.fields(entity)
                )
                self._conn.execute(
                    f'CREATE TABLE IF NOT EXISTS "{entity}" '
                    f"(id INTEGER PRIMARY KEY AUTOINCREMENT, {cols})"
                )

    def close(self) -> None:
        self._conn.close()

    def _to_dict(self, entity: str, row: sqlite3.Row) -> dict:
        record = {"id": row["id"]}
        for f in models.fields(entity):
            value = row[f["name"]]
            if f["type"] == "bool" and value is not None:
                value = bool(value)
            record[f["name"]] = value
        return record

    def create(self, entity: str, data: dict) -> dict:
        clean = models.validate(entity, data)
        names = list(clean)
        cols = ", ".join(f'"{n}"' for n in names)
        marks = ", ".join("?" for _ in names)
        with self._lock, self._conn:
            cur = self._conn.execute(
                f'INSERT INTO "{entity}" ({cols}) VALUES ({marks})', [clean[n] for n in names]
            )
            new_id = cur.lastrowid
        return self.get(entity, new_id)

    def get(self, entity: str, item_id: int) -> dict | None:
        models.fields(entity)
        with self._lock:
            row = self._conn.execute(
                f'SELECT * FROM "{entity}" WHERE id = ?', (item_id,)
            ).fetchone()
        return self._to_dict(entity, row) if row else None

    def list(self, entity: str, filters: dict | None = None) -> list[dict]:
        """All records, oldest first. ``filters`` are field=value equality checks."""
        models.fields(entity)
        where, params = "", []
        if filters:
            clean = models.validate(entity, filters, partial=True)
            where = " WHERE " + " AND ".join(f'"{n}" IS ?' for n in clean)
            params = list(clean.values())
        with self._lock:
            rows = self._conn.execute(
                f'SELECT * FROM "{entity}"{where} ORDER BY id', params
            ).fetchall()
        return [self._to_dict(entity, r) for r in rows]

    def update(self, entity: str, item_id: int, data: dict, *, partial: bool = True) -> dict | None:
        """Change a record. Returns None when the id does not exist."""
        if self.get(entity, item_id) is None:
            return None
        clean = models.validate(entity, data, partial=partial)
        sets = ", ".join(f'"{n}" = ?' for n in clean)
        with self._lock, self._conn:
            self._conn.execute(
                f'UPDATE "{entity}" SET {sets} WHERE id = ?', [*clean.values(), item_id]
            )
        return self.get(entity, item_id)

    def delete(self, entity: str, item_id: int) -> bool:
        models.fields(entity)
        with self._lock, self._conn:
            cur = self._conn.execute(f'DELETE FROM "{entity}" WHERE id = ?', (item_id,))
        return cur.rowcount > 0
'''

