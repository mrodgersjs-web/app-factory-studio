def render_common(plan: Plan) -> dict[str, str]:
    subs = header(plan)
    subs["__SCHEMA__"] = pylit(schema_literal(plan))
    pkg = f"src/{plan.package}"
    init_doc = f'"""{plan.name}.\n\n{textwrap.fill(plan.description, 88)}\n"""\n'
    return {
        f"{pkg}/__init__.py": init_doc + '\n__version__ = "0.1.0"\n',
        f"{pkg}/models.py": fill(MODELS_PY, subs),
        f"{pkg}/store.py": fill(STORE_PY, subs),
        "tests/conftest.py": fill(CONFTEST_PY, subs),
        "tests/test_models.py": render_test_models(plan),
        "tests/test_store.py": render_test_store(plan),
        ".gitignore": "__pycache__/\n.pytest_cache/\n*.db\n*.egg-info/\n.venv/\n",
    }
