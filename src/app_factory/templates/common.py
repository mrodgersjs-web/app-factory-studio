def header(plan: Plan) -> dict[str, str]:
    return {
        "__NAME__": plan.name,
        "__PKG__": plan.package,
        "__VERSION__": plan.factory_version,
        "__SHA12__": plan.spec_sha256[:12],
    }


def fill(text: str, subs: dict[str, str]) -> str:
    for key, value in subs.items():
        text = text.replace(key, value)
    return text


def sample_constants(plan: Plan) -> str:
    """Module-level sample data shared by the generated tests."""
    lines = []
    for e in plan.entities:
        up = e.name.upper()
        a, b = sample(e, 0), sample(e, 1)
        bad = {f.name: INVALID[f.type] for f in e.fields}
        required = sorted(f.name for f in e.fields if f.required)
        key = e.fields[0].name
        lines += [
            f"{up}_A = {pylit(a)}",
            f"{up}_B = {pylit(b)}",
            f"{up}_BAD = {pylit(bad)}",
            f"{up}_REQUIRED = {pylit(required)}",
            f"{up}_KEY = {key!r}",
            f"{up}_KEY_TEXT_B = {cli_value(b[key])!r}",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def render_test_models(plan: Plan) -> str:
    out = [
        '"""Schema validation tests (generated)."""',
        "",
        "import pytest",
        "",
        f"from {plan.package} import models",
        "",
        sample_constants(plan),
    ]
    for e in plan.entities:
        n, up = e.name, e.name.upper()
        texts = {f.name: cli_value(v) for f, v in zip(e.fields, sample(e, 0).values(), strict=True)}
        out.append(f'''
def test_{n}_valid_sample_accepted():
    assert models.validate("{n}", {up}_A) == {up}_A


def test_{n}_text_inputs_are_coerced():
    texts = {pylit(texts, 4)}
    assert models.validate("{n}", texts) == {up}_A


def test_{n}_missing_required_rejected():
    with pytest.raises(models.ValidationError) as info:
        models.validate("{n}", {{}})
    assert sorted(info.value.errors) == {up}_REQUIRED


def test_{n}_bad_values_rejected():
    with pytest.raises(models.ValidationError) as info:
        models.validate("{n}", {up}_BAD)
    assert sorted(info.value.errors) == sorted({up}_BAD)


def test_{n}_unknown_field_rejected():
    with pytest.raises(models.ValidationError) as info:
        models.validate("{n}", dict({up}_A, not_a_field="x"))
    assert info.value.errors == {{"not_a_field": "unknown field"}}


def test_{n}_partial_checks_only_given_fields():
    assert models.validate("{n}", {{{up}_KEY: {up}_B[{up}_KEY]}}, partial=True) == {{
        {up}_KEY: {up}_B[{up}_KEY]
    }}
    with pytest.raises(models.ValidationError):
        models.validate("{n}", {{}}, partial=True)
''')
    return "\n".join(out).rstrip() + "\n"


def render_test_store(plan: Plan) -> str:
    out = [
        '"""SQLite store tests (generated)."""',
        "",
        "import pytest",
        "",
        f"from {plan.package} import models",
        f"from {plan.package}.store import Store",
        "",
        sample_constants(plan),
    ]
    for e in plan.entities:
        n, up = e.name, e.name.upper()
        out.append(f'''
def test_{n}_create_and_get(store):
    created = store.create("{n}", {up}_A)
    assert created["id"] == 1
    assert {{k: created[k] for k in {up}_A}} == {up}_A
    assert store.get("{n}", created["id"]) == created


def test_{n}_list_and_filter(store):
    a = store.create("{n}", {up}_A)
    b = store.create("{n}", {up}_B)
    assert [r["id"] for r in store.list("{n}")] == [a["id"], b["id"]]
    assert [r["id"] for r in store.list("{n}", {{{up}_KEY: {up}_KEY_TEXT_B}})] == [b["id"]]


def test_{n}_update_partial_and_full(store):
    a = store.create("{n}", {up}_A)
    updated = store.update("{n}", a["id"], {{{up}_KEY: {up}_B[{up}_KEY]}})
    assert updated[{up}_KEY] == {up}_B[{up}_KEY]
    for name, value in {up}_A.items():
        if name != {up}_KEY:
            assert updated[name] == value
    full = store.update("{n}", a["id"], {up}_B, partial=False)
    assert {{k: full[k] for k in {up}_B}} == {up}_B
    assert store.update("{n}", 999, {{{up}_KEY: {up}_B[{up}_KEY]}}) is None


def test_{n}_delete(store):
    a = store.create("{n}", {up}_A)
    assert store.delete("{n}", a["id"]) is True
    assert store.get("{n}", a["id"]) is None
    assert store.delete("{n}", a["id"]) is False


def test_{n}_invalid_data_not_stored(store):
    with pytest.raises(models.ValidationError):
        store.create("{n}", {up}_BAD)
    assert store.list("{n}") == []


def test_{n}_persists_to_file(tmp_path):
    path = str(tmp_path / "app.db")
    first = Store(path)
    created = first.create("{n}", {up}_A)
    first.close()
    second = Store(path)
    try:
        assert second.get("{n}", created["id"]) == created
    finally:
        second.close()
''')
    return "\n".join(out).rstrip() + "\n"


