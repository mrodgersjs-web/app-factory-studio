"""Write a generated app, run its tests, and seal (or refuse) a proof.

Fail-closed rules:

* success needs pytest exit 0, zero failures/errors, and exactly the number of
  tests the factory generated (deleted or skipped tests do not count as passing);
* ``prove`` needs a PASS proof whose tree hash equals the files on disk now, and
  (unless ``allow_modified``) files that still match the generation manifest.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

from . import __version__
from .render import render
from .spec import Plan

MANIFEST = "app-factory.json"
PROOF = "proofs/proof.json"
SKIP_DIRS = {"__pycache__", ".pytest_cache", "proofs", ".venv", ".ruff_cache"}
SKIP_SUFFIXES = (".pyc", ".db", ".egg-info")
TEST_DEF = re.compile(r"^def test_", re.M)


class GateError(RuntimeError):
    """The output location or app state does not allow the requested step."""


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def tree_files(root: Path) -> dict[str, str]:
    """{relative path: sha256} for app files (skips caches, proofs, db files, manifest)."""
    out: dict[str, str] = {}
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS or part.endswith(".egg-info") for part in rel.parts):
            continue
        if not path.is_file() or rel.as_posix() == MANIFEST or path.name.endswith(SKIP_SUFFIXES):
            continue
        out[rel.as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return out


def tree_hash(files: dict[str, str]) -> str:
    joined = "".join(f"{path}\0{digest}\n" for path, digest in sorted(files.items()))
    return sha256_text(joined)


def count_tests(files: dict[str, str]) -> int:
    return sum(len(TEST_DEF.findall(text)) for path, text in files.items() if path.startswith("tests/test_"))


def write_app(plan: Plan, out: Path) -> dict:
    """Render and write the app plus its manifest. Returns the manifest."""
    files = render(plan)
    if out.exists() and any(out.iterdir()):
        if not (out / MANIFEST).exists():
            raise GateError(f"{out} is not empty and was not made by app-factory; choose another --out")
        shutil.rmtree(out)
    for rel, text in files.items():
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    digests = {rel: sha256_text(text) for rel, text in files.items()}
    manifest = {
        "schema": "app-factory.manifest.v1",
        "factory_version": __version__,
        "plan": plan.to_dict(),
        "expected_tests": count_tests(files),
        "files": digests,
        "tree_sha256": tree_hash(digests),
    }
    (out / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def load_manifest(root: Path) -> dict:
    path = root / MANIFEST
    if not path.exists():
        raise GateError(f"{path} not found: this directory was not generated by app-factory")
    return json.loads(path.read_text(encoding="utf-8"))


def parse_pytest_summary(output: str) -> dict:
    counts = {"passed": 0, "failed": 0, "errors": 0, "skipped": 0, "xfailed": 0, "xpassed": 0}
    summary = ""
    for line in reversed(output.strip().splitlines()):
        if re.search(r"\b(passed|failed|error|errors|skipped|no tests ran)\b", line):
            summary = line.strip("= ").strip()
            break
    for num, word in re.findall(r"(\d+) (passed|failed|errors?|skipped|xfailed|xpassed)", summary):
        key = "errors" if word.startswith("error") else word
        counts[key] = int(num)
    stable = re.sub(r"\s+in [\d.]+s.*$", "", summary)
    return {"counts": counts, "summary": stable}


def run_tests(root: Path, timeout: int = 600) -> dict:
    """Run the generated app's own tests with this Python. Never raises on test failure."""
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    env.pop("PYTHONPATH", None)
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-p", "no:randomly", "tests"]
    try:
        proc = subprocess.run(cmd, cwd=root, env=env, capture_output=True, text=True, timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return {"exit_code": None, "counts": {}, "summary": f"timed out after {timeout}s", "output_tail": ""}
    output = proc.stdout + proc.stderr
    parsed = parse_pytest_summary(proc.stdout)
    if proc.returncode != 0 and "No module named pytest" in output:
        parsed["summary"] = "pytest is not installed for this Python (pip install pytest)"
    return {"exit_code": proc.returncode, **parsed, "output_tail": output[-4000:]}


def verify(root: Path) -> dict:
    """Run the tests and write proofs/proof.json. ``verdict`` is PASS only if every rule holds."""
    manifest = load_manifest(root)
    current = tree_files(root)
    drift = sorted(
        set(manifest["files"]) ^ set(current)
        | {p for p in manifest["files"] if p in current and current[p] != manifest["files"][p]}
    )
    result = run_tests(root)
    counts = result.get("counts", {})
    expected = manifest["expected_tests"]
    reasons = []
    if result["exit_code"] != 0:
        reasons.append(f"pytest exit code {result['exit_code']}")
    if counts.get("failed") or counts.get("errors"):
        reasons.append(f"{counts.get('failed', 0)} failed, {counts.get('errors', 0)} errors")
    if counts.get("passed", 0) != expected:
        reasons.append(f"{counts.get('passed', 0)} passed but the factory generated {expected} tests")
    proof = {
        "schema": "app-factory.proof.v1",
        "factory_version": __version__,
        "app": manifest["plan"]["name"],
        "template": manifest["plan"]["template"],
        "spec_sha256": manifest["plan"]["spec_sha256"],
        "tree_sha256": tree_hash(current),
        "matches_manifest": not drift,
        "drift": drift,
        "expected_tests": expected,
        "tests": counts,
        "pytest_summary": result["summary"],
        "pytest_exit_code": result["exit_code"],
        "python": f"{sys.version_info.major}.{sys.version_info.minor}",
        "verdict": "FAIL" if reasons else "PASS",
        "reasons": reasons,
    }
    (root / "proofs").mkdir(exist_ok=True)
    (root / PROOF).write_text(json.dumps(proof, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if reasons:
        proof["output_tail"] = result["output_tail"]
    return proof


def prove(root: Path, allow_modified: bool = False) -> dict:
    """Check a sealed proof without re-running tests."""
    problems = []
    try:
        manifest = load_manifest(root)
    except GateError as exc:
        return {"ok": False, "path": str(root), "problems": [str(exc)]}
    proof_path = root / PROOF
    if not proof_path.exists():
        return {"ok": False, "path": str(root), "problems": [f"{PROOF} missing: run app-factory verify"]}
    proof = json.loads(proof_path.read_text(encoding="utf-8"))
    current = tree_files(root)
    if proof.get("verdict") != "PASS":
        problems.append(f"proof verdict is {proof.get('verdict')}: {'; '.join(proof.get('reasons', []))}")
    if proof.get("tree_sha256") != tree_hash(current):
        problems.append("files changed since the proof was sealed: run app-factory verify again")
    if not allow_modified and tree_hash(current) != manifest["tree_sha256"]:
        problems.append("files differ from the generation manifest (use --allow-modified for edited apps)")
    return {
        "ok": not problems,
        "path": str(root),
        "app": manifest["plan"]["name"],
        "tree_sha256": tree_hash(current),
        "tests": proof.get("tests"),
        "problems": problems,
    }
